-- 방. 큐 자체는 Redis 에 있고(ADR 0001), 여기에는 방의 정체와 수명만 둔다.
create table room (
    id              bigint generated by default as identity primary key,
    code            varchar(6)  not null,
    mode            varchar(20) not null,
    -- 호스트의 참여자 ID. 로그인이 없는 M1 에서는 익명 세션의 ID 라서 user 테이블을 참조하지 않는다.
    host_id         uuid        not null,
    player_provider varchar(20) not null,
    status          varchar(20) not null,
    expires_at      timestamptz not null,
    created_at      timestamptz not null,
    -- 코드 중복을 막는 최종 방어선. 동시에 같은 코드를 뽑은 두 요청 중 하나는 여기서 실패하고 재시도한다.
    constraint uk_room_code unique (code)
);
